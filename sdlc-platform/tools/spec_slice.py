#!/usr/bin/env python
"""Build the input slice for ONE feature-spec writer: 02-spec/slices/F-nnn.md.

Instead of every parallel writer reading the whole FRD, architecture and contracts, each one reads
only its slice:
  - the feature entry (description, entities, endpoints, screens)
  - the full text of its requirements (statement, acceptance criteria, notes, clarifications)
  - the client paragraphs those requirements cite (C-nnn, verbatim from crd-index.json)
  - the open questions about them
  - its tables from schema.sql, its operations (tag F-nnn) and referenced schemas from openapi.yaml
  - its screens from ui-spec.md
  - its dependency edges (when dependencies.json exists)
  - the architecture sections every writer needs (project structure, cross-cutting, MVC layers)
  - existing-code facts about its entities (existing projects only)

Usage: spec_slice.py F-nnn|all [--project ID]   (also: spec_docs.py slice F-nnn|all)
"""
from __future__ import annotations

import argparse
import re
from pathlib import Path

from common import project_dir, read_json, rel
from spec_rules import Ctx, table_candidates, snake

ARCH_SECTIONS = re.compile(r"(?i)project structure|cross-cutting|mvc|layer|error|auth|security|validation")


def _md_sections(text: str, level: int = 2):
    """Yield (heading line, full section text) for headings of the given level."""
    pat = re.compile(rf"^{'#' * level}\s+.+$", re.M)
    starts = [m.start() for m in pat.finditer(text)] + [len(text)]
    for a, b in zip(starts, starts[1:]):
        chunk = text[a:b]
        yield chunk.splitlines()[0], chunk.rstrip()


def _refs(obj, found: set):
    if isinstance(obj, dict):
        for k, v in obj.items():
            if k == "$ref" and isinstance(v, str):
                found.add(v.rsplit("/", 1)[-1])
            else:
                _refs(v, found)
    elif isinstance(obj, list):
        for v in obj:
            _refs(v, found)


def build_slice(pdir: Path, fid: str) -> str:
    import yaml
    ctx = Ctx(pdir)
    feat = next((f for f in ctx.features if f["id"] == fid), None)
    if feat is None:
        raise SystemExit(f"{fid} not in features.json")
    out = [f"# Input slice for {fid}: {feat['title']}", "",
           "Generated by `tools/spec_slice.py`. This is everything the feature-spec writer needs; "
           "do not read the full FRD.", "", "## Feature", "", feat.get("description", ""), ""]
    for k in ("layers", "entities", "endpoints", "screens"):
        if feat.get(k):
            out.append(f"- {k.capitalize()}: " + ", ".join(feat[k]))
    out += ["", "## Requirements (approved FRD)", ""]
    cids = []
    for rid in feat["requirement_ids"]:
        r = ctx.reqs.get(rid)
        if not r:
            out.append(f"### {rid}: NOT IN THE APPROVED FRD")
            continue
        out += [f"### {rid}: {r['title']}", "",
                f"- Type {r['type']}, priority {r['priority']}, status {r['status']}"
                + (f", client ref {r['client_ref']}" if r.get("client_ref") else ""),
                f"- Source: {', '.join(r['source'])}", f"- Statement: {r['statement']}"]
        out += [f"- Acceptance: {ac}" for ac in r.get("acceptance_criteria", [])]
        for k in ("clarification", "notes"):
            if r.get(k):
                out.append(f"- {k.capitalize()}: {r[k]}")
        out.append("")
        cids += [s for s in r["source"] if s.startswith("C-") and s not in cids]
    if cids:
        out += ["## Client text cited by these requirements", ""]
        for c in cids:
            b = ctx.blocks.get(c, {})
            out += [f"[{c}] {b.get('text', '(missing)')}", ""]
    own = set(feat["requirement_ids"])
    qs = [q for q in ctx.frd.get("open_questions", [])
          if own & set(q.get("related", [])) or set(cids) & set(q.get("source", []))]
    if qs:
        out += ["## Open questions about these requirements", ""]
        out += [f"- {q['id']} ({'blocking' if q.get('blocking') else 'non-blocking'}): {q['question']}"
                + (f" **Resolution:** {q['resolution']}" if q.get("resolution") else "") for q in qs]
        out.append("")
    ents = feat.get("entities", [])
    tbls = [(t, ctx.tables[t]) for e in ents for t in sorted(table_candidates(e)) if t in ctx.tables]
    if tbls:
        out += ["## Database (from schema.sql)", "", "```sql"]
        out += [f"{d['comment']}\n{d['statement']}".strip() for _, d in tbls]
        out += ["```", ""]
    ops, refs = {}, set()
    for path, item in (ctx.api.get("paths") or {}).items():
        for method, op in (item or {}).items():
            if isinstance(op, dict) and fid in (op.get("tags") or []):
                ops.setdefault(path, {})[method] = op
                _refs(op, refs)
    schemas = (ctx.api.get("components") or {}).get("schemas") or {}
    todo, seen = list(refs), set()
    while todo:
        n = todo.pop()
        if n in seen or n not in schemas:
            continue
        seen.add(n)
        more = set()
        _refs(schemas[n], more)
        todo += list(more - seen)
    if ops:
        out += ["## API (operations tagged " + fid + " in openapi.yaml)", "", "```yaml",
                yaml.safe_dump({"paths": ops, "components": {"schemas": {n: schemas[n] for n in sorted(seen)}}},
                               sort_keys=False, allow_unicode=True).rstrip(), "```", ""]
    if ctx.ui and feat.get("screens"):
        picked = [body for head, body in _md_sections(ctx.ui, 3)
                  if fid in head or any(s.lower() in head.lower() for s in feat["screens"])]
        if picked:
            out += ["## UI (screens from ui-spec.md)", ""] + picked + [""]
    from wireframes import approved_screens
    wf = [s for s in approved_screens(pdir) if s["name"].lower() in {x.lower() for x in feat.get("screens", [])}]
    if wf:
        out += ["## Approved wireframes (binding layout; open the HTML)", ""]
        out += [f"- {s['id']} {s['name']} ({', '.join(s['roles'])}): `{s['path']}`; requirements "
                f"{', '.join(s['requirement_ids'])}" for s in wf] + [""]
    deps = read_json(ctx.sdir / "dependencies.json", default={}).get("edges", [])
    mine = [e for e in deps if fid in (e.get("from"), e.get("to"))]
    if mine:
        out += ["## Dependencies", ""] + [f"- {e['from']} -> {e['to']} ({e['type']}): {e.get('reason', '')}"
                                          for e in mine] + [""]
    arch = ctx.sdir / "architecture.md"
    if arch.exists():
        picked = [body for head, body in _md_sections(arch.read_text(encoding="utf-8"), 2) if ARCH_SECTIONS.search(head)]
        if picked:
            out += ["## Architecture excerpts (architecture.md)", ""] + picked + [""]
    if ctx.facts:
        keys = {snake(e) for e in ents} | {t for e in ents for t in table_candidates(e)}
        hits = [f"- table {t['name']} ({t['file']})" for t in ctx.facts.get("tables", []) if t["name"].lower() in keys]
        hits += [f"- {c['kind']} {c['name']} ({c['file']})" for c in ctx.facts.get("classes", [])
                 if any(k.replace("_", "") in c["name"].lower() for k in keys)]
        if hits:
            out += ["## Existing code for these entities (modify, do not re-create)", ""] + hits + [""]
    return "\n".join(out).rstrip() + "\n"


def write_slice(pdir: Path, fid: str):
    text = build_slice(pdir, fid)
    out = pdir / "02-spec" / "slices" / f"{fid}.md"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(text, encoding="utf-8")
    return out, len(text.encode("utf-8"))


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("feature")
    ap.add_argument("--project")
    a = ap.parse_args()
    pdir = project_dir(a.project)
    ids = [f["id"] for f in Ctx(pdir).features] if a.feature == "all" else [a.feature]
    for fid in ids:
        out, size = write_slice(pdir, fid)
        print(f"wrote {rel(out)} ({size // 1024} KB)")


if __name__ == "__main__":
    main()
